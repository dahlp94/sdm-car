def json_save(path, obj):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=2, sort_keys=True, default=str), encoding='utf-8')


def as_float(x):
    return float(x.detach().cpu().item()) if torch.is_tensor(x) else float(x)


def sha256(path):
    h=hashlib.sha256()
    with path.open('rb') as f:
        for chunk in iter(lambda:f.read(2**20),b''):
            h.update(chunk)
    return h.hexdigest()


def read_checkpoint(exp, path, *, seed, model_tag, digest):
    if not path.exists():
        raise FileNotFoundError(f'Missing saved baseline checkpoint: {path}')
    state=exp.load_trusted_checkpoint(path)
    assert state['experiment_version'] == exp.EXPERIMENT_VERSION, f'Version mismatch: {path}'
    assert state['label'] == MODEL_LABELS[model_tag], f'Model label mismatch: {path}'
    assert state['data_digest'] == digest, f'Data/graph hash mismatch: {path}'
    if 'num_mc' in state:
        assert int(state['num_mc']) == exp.NUM_MC, f'VI num_mc mismatch: {path}'
    return state


