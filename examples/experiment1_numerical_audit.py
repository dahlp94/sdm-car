"""Independent numerical audit for Experiment 1 (N=144, fixed beta=0).

Run from the ORIGINAL sd m-car project root. Does not alter any final-run
checkpoints, results, optimization code, or scientific conclusions.

Three separately controlled checks:
  * continue: exact-optimizer/RNG-state continuation of the fitted models;
  * restarts: fresh SDM fits, with changed initial parameters but the SAME
    stochastic optimizer seed, plus one unchanged-initialization/different-RNG
    control. All use exactly the original generated dataset for each seed;
  * evaluate: paired common-random-number comparisons to the original saved
    checkpoints using the true fixed-intercept Gaussian conditional oracle.

This code requires trusted local .pt checkpoint files generated by the user's
original Experiment 1 script. torch.load of untrusted pickle files is unsafe.
"""
